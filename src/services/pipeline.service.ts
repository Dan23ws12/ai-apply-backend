import { prisma } from "../lib/prisma.js";
import { logger } from "../lib/logger.js";
import { HttpError, notFound } from "../lib/errors.js";
import { aiClient } from "./ai.client.js";
import { audit } from "./audit.service.js";
import { jobForAi, loadApplicant } from "./applicant.service.js";
import { blacklistedCompanyIds, isBlacklisted } from "./blacklist.service.js";
import { pickApplyOption, searchJobs } from "./search/jobSearch.service.js";
import { normalizeCompanyName } from "./search/normalize.js";

interface Ctx {
  userId: string;
  requestId?: string;
}

/**
 * Step 1 (runs during the HTTP request): search, filter, and save new jobs.
 * Step 2 (runs in the background): score each new job, then create documents for good matches.
 */
export async function runSearchCriteria(criteriaId: string, ctx: Ctx) {
  const criteria = await prisma.searchCriteria.findFirst({ where: { id: criteriaId, userId: ctx.userId } });
  if (!criteria) throw notFound("Search criteria");

  const { provider, totalFound, jobs } = await searchJobs(criteria, ctx);
  const newJobIds: string[] = [];
  const blacklist = await blacklistedCompanyIds(ctx.userId);

  for (const j of jobs) {
    const normalizedName = normalizeCompanyName(j.companyName) || j.companyName.toLowerCase();
    const company = await prisma.company.upsert({
      where: { normalizedName },
      create: { name: j.companyName, normalizedName, websiteUrl: j.companyWebsite },
      update: j.companyWebsite ? { websiteUrl: j.companyWebsite } : {},
    });

    const exists = await prisma.job.findUnique({
      where: { userId_externalId: { userId: ctx.userId, externalId: j.externalId } },
      select: { id: true },
    });
    if (exists) continue;

    const apply = pickApplyOption(j.applyOptions, criteria.websites);
    if (!apply) continue;
    const listedOn = j.applyOptions.find((o) => criteria.websites.includes(o.website)) ?? apply;
    const blacklisted = blacklist.has(company.id);

    const job = await prisma.job.create({
      data: {
        userId: ctx.userId,
        companyId: company.id,
        companyName: company.name,
        searchCriteriaId: criteria.id,
        externalId: j.externalId,
        provider: j.provider,
        positionName: j.positionName,
        description: j.description,
        location: j.location,
        jobType: j.jobType,
        locationType: j.locationType,
        searchWebsite: listedOn.website,
        applicationLink: apply.url,
        applyOptions: j.applyOptions as object[],
        salaryMin: j.salaryMin,
        salaryMax: j.salaryMax,
        salaryCurrency: j.salaryCurrency,
        salaryPeriod: j.salaryPeriod,
        postedAt: j.postedAt,
        applicationStatus: blacklisted ? "SKIPPED" : "FOUND",
        statusMessage: blacklisted ? "Company is blacklisted" : null,
      },
    });
    if (!blacklisted) newJobIds.push(job.id);
  }

  await prisma.searchCriteria.update({ where: { id: criteria.id }, data: { lastRunAt: new Date() } });

  // Background work: don't make the HTTP request wait for AI calls.
  void processJobs(newJobIds, criteria, ctx);

  return { provider, totalFound, saved: newJobIds.length, jobIds: newJobIds };
}

async function processJobs(
  jobIds: string[],
  criteria: { minMatchRating: number; maxFraudRating: number; autoGenerateDocs: boolean },
  ctx: Ctx,
) {
  for (const jobId of jobIds) {
    try {
      const scored = await scoreJob(jobId, ctx);
      const passes = scored.match_rating >= criteria.minMatchRating && scored.fraud_rating <= criteria.maxFraudRating;
      if (!passes) {
        await prisma.job.update({
          where: { id: jobId },
          data: {
            applicationStatus: "SKIPPED",
            statusMessage: `Match ${scored.match_rating} (min ${criteria.minMatchRating}), fraud ${scored.fraud_rating} (max ${criteria.maxFraudRating})`,
          },
        });
        continue;
      }
      if (criteria.autoGenerateDocs) await generateDocuments(jobId, ctx, scored);
    } catch (err) {
      logger.error({ err, jobId }, "Processing job failed");
      await markError(jobId, err, ctx);
    }
  }
}

export async function scoreJob(jobId: string, ctx: Ctx) {
  const job = await prisma.job.findFirstOrThrow({ where: { id: jobId, userId: ctx.userId }, include: { company: true } });
  const profile = await prisma.userProfile.findUnique({ where: { userId: ctx.userId } });
  const result = await aiClient.score({ job: jobForAi(job), preferred_category: profile?.defaultResumeCategory }, ctx);
  await prisma.job.update({
    where: { id: jobId },
    data: {
      matchRating: result.match_rating,
      matchReason: result.match_reason,
      fraudRating: result.fraud_rating,
      fraudReason: result.fraud_reason,
    },
  });
  return result;
}

/** Creates a tailored resume + cover letter and stores the links in application_files. */
export async function generateDocuments(
  jobId: string,
  ctx: Ctx,
  scored?: { resume_category: string; keywords: string[] },
) {
  const job = await prisma.job.findFirst({ where: { id: jobId, userId: ctx.userId }, include: { company: true } });
  if (!job) throw notFound("Job");
  if (await isBlacklisted(ctx.userId, job.companyId)) throw new HttpError(409, "Company is blacklisted");

  const score = scored ?? (await scoreJob(jobId, ctx));
  const applicant = await loadApplicant(ctx.userId);
  const docs = await aiClient.documents(
    { job_id: job.id, job: jobForAi(job), applicant, resume_category: score.resume_category, keywords: score.keywords },
    ctx,
  );

  // Regenerating replaces the AI versions but keeps a custom file the user picked.
  const existing = await prisma.applicationFile.findUnique({ where: { jobId } });
  const resumeIsCustom = !!existing?.resumeLink && existing.resumeLink !== existing.aiResumeLink;
  const coverIsCustom = !!existing?.coverLetterLink && existing.coverLetterLink !== existing.aiCoverLetterLink;
  const data = {
    resumeLink: resumeIsCustom ? existing!.resumeLink : docs.resume_path,
    coverLetterLink: coverIsCustom ? existing!.coverLetterLink : docs.cover_letter_path,
    aiResumeLink: docs.resume_path,
    aiCoverLetterLink: docs.cover_letter_path,
    baseResumeCategory: docs.resume_category,
    keywordsUsed: docs.keywords_used,
  };
  await prisma.applicationFile.upsert({ where: { jobId }, create: { jobId, ...data }, update: data });

  await prisma.job.update({
    where: { id: jobId },
    data: { applicationStatus: "DOCUMENTS_READY", statusMessage: null },
  });
  return prisma.applicationFile.findUniqueOrThrow({ where: { jobId } });
}

export async function markError(jobId: string, err: unknown, ctx: Ctx) {
  const message = (err as Error)?.message ?? String(err);
  audit({ type: "ERROR", userId: ctx.userId, requestId: ctx.requestId, message: `job ${jobId}: ${message}` });
  await prisma.job
    .update({ where: { id: jobId }, data: { applicationStatus: "ERROR", statusMessage: message.slice(0, 2000) } })
    .catch(() => undefined);
}
