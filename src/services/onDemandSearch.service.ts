import type { SearchCriteria } from "../generated/prisma/client.js";
import { prisma } from "../lib/prisma.js";
import { logger } from "../lib/logger.js";
import type { JobSearchBody } from "../schemas/jobs.js";
import { blacklistedCompanyNames } from "./blacklist.service.js";
import { toClientJob } from "./clientJob.js";
import { jobInclude, upsertPosting } from "./jobs.service.js";
import { SKIP_MATCH_FRAUD_RATING, evaluateJob } from "./pipeline.service.js";
import { getUserSettings } from "./settings.service.js";
import { isBlockedName } from "./search/companyName.js";
import { boardWebsite, pickApplyOption, searchJobs } from "./search/jobSearch.service.js";
import { normalizeCompanyName } from "./search/normalize.js";

/**
 * POST /api/jobs/search: runs a search now and returns the jobs, without saving search
 * criteria. Uses the same search cache and API fallback as saved searches.
 *
 * Every returned job is stored as this user's job (status FOUND), so it has an id the app
 * can save, apply to, rate and generate documents for. Jobs the user already has come back
 * with their current status and ratings. Blacklisted companies are left out.
 * New jobs are rated in the background (fraud first, then match), so their ratings are
 * null in this reply; GET /api/jobs/:id shows them once ready.
 */
export async function searchOnDemand(userId: string, body: JobSearchBody, requestId?: string) {
  const settings = await getUserSettings(userId);
  const limit = body.limit ?? settings.jobsPerSearch;
  const now = new Date();

  // A search the user didn't save, in the shape the search service expects.
  const criteria: SearchCriteria = {
    id: "on-demand",
    userId,
    name: "On-demand search",
    query: body.query,
    location: body.location || null,
    country: body.country,
    datePosted: body.datePosted,
    jobTypes: body.employmentTypes,
    locationTypes: body.workModels,
    websites: body.websites,
    includeKeywords: body.includeKeywords,
    excludeKeywords: body.excludeKeywords,
    minSalary: null,
    minMatchRating: 0,
    maxFraudRating: 100,
    maxResults: limit,
    autoGenerateDocs: false,
    isActive: true,
    lastRunAt: null,
    createdAt: now,
    updatedAt: now,
  };

  const blocked = await blacklistedCompanyNames(userId);
  const companyKey = (name: string) => normalizeCompanyName(name) || name.toLowerCase();
  const ownedIds = async (externalIds: string[]) =>
    new Set(
      (
        await prisma.application.findMany({
          where: { userId, posting: { externalId: { in: externalIds } } },
          select: { posting: { select: { externalId: true } } },
        })
      ).map((r) => r.posting.externalId),
    );

  const outcome = await searchJobs(criteria, { userId, requestId }, {
    pages: settings.pagesPerSearch,
    // Cached jobs that are new to this user; fewer than the refresh threshold fetches the next page.
    countOpenJobs: async (matching) => {
      const owned = await ownedIds(matching.map((j) => j.externalId));
      return matching.filter((j) => !owned.has(j.externalId) && !isBlockedName(blocked, j.companyName)).length;
    },
  });

  const postedAfter = body.postedAfter ? new Date(body.postedAfter) : null;
  const candidates = outcome.jobs.filter(
    (j) => !isBlockedName(blocked, j.companyName) && (!postedAfter || !j.postedAt || j.postedAt >= postedAfter),
  );

  const ids: string[] = [];
  const newIds: string[] = [];
  for (const j of candidates) {
    if (ids.length >= limit) break;
    const apply = pickApplyOption(j.applyOptions, body.websites);
    if (!apply) continue;

    const normalizedName = companyKey(j.companyName);
    const company = await prisma.company.upsert({
      where: { normalizedName },
      create: { name: j.companyName, normalizedName, websiteUrl: j.companyWebsite },
      update: j.companyWebsite ? { websiteUrl: j.companyWebsite } : {},
    });
    const posting = await upsertPosting(j, company.id, j.companyName);
    const existing = await prisma.application.findUnique({
      where: { userId_postingId: { userId, postingId: posting.id } },
      select: { id: true },
    });
    if (existing) {
      ids.push(existing.id);
      continue;
    }
    const applyOption = posting.applyOptions.find((o) => o.url === apply.url);
    if (!applyOption) continue;
    const foundOn = boardWebsite(j, body.websites) ?? apply.website;
    const app = await prisma.application.create({
      data: {
        userId,
        postingId: posting.id,
        applyOptionId: applyOption.id,
        searchWebsite: foundOn,
        applicationStatus: "FOUND",
        statusEvents: { create: { fromStatus: null, toStatus: "FOUND", message: "Found by on-demand search" } },
      },
    });
    ids.push(app.id);
    newIds.push(app.id);
  }

  const rows = await prisma.application.findMany({ where: { id: { in: ids } }, include: jobInclude });
  const byId = new Map(rows.map((r) => [r.id, r]));
  const jobs = ids.map((id) => byId.get(id)).filter((r): r is NonNullable<typeof r> => !!r);

  if (body.evaluate) {
    // Rate jobs that have no rating yet: new ones, and older ones that were never rated.
    const toRate = jobs
      .filter((r) => r.posting.fraudRating == null || (r.matchRating == null && r.posting.fraudRating < SKIP_MATCH_FRAUD_RATING))
      .filter((r) => r.applicationStatus !== "APPLIED")
      .map((r) => r.id);
    void rateInBackground(toRate, { userId, requestId });
  }

  return {
    jobs: jobs.map(toClientJob),
    meta: {
      provider: outcome.provider,
      source: outcome.source,
      apiCalled: outcome.apiCalled,
      totalFound: outcome.totalFound,
      matching: outcome.jobs.length,
      returned: jobs.length,
      newJobs: newIds.length,
      warning: outcome.warning ?? null,
    },
  };
}

async function rateInBackground(ids: string[], ctx: { userId: string; requestId?: string }) {
  for (const id of ids) {
    try {
      await evaluateJob(id, ctx);
    } catch (err) {
      logger.warn({ err: (err as Error).message, jobId: id }, "Rating an on-demand search result failed");
    }
  }
}
