/**
 * Zod schemas for every request the API accepts.
 * Zod validates input; authentication itself is done with bcrypt + JWT (see middleware/auth.ts).
 */
import { z } from "zod";

// ── shared ──
export const IdParams = z.object({ id: z.uuid() });
export const FileParams = z.object({ id: z.uuid(), kind: z.enum(["resume", "cover-letter"]) });

const JobTypeEnum = z.enum(["FULL_TIME", "PART_TIME", "CONTRACT", "INTERNSHIP", "TEMPORARY", "OTHER", "UNKNOWN"]);
const LocationTypeEnum = z.enum(["HYBRID", "REMOTE", "ON_SITE", "UNKNOWN"]);
const WebsiteEnum = z.enum(["LINKEDIN", "GLASSDOOR", "INDEED", "COMPANY_SITE", "OTHER"]);
const DatePostedEnum = z.enum(["PAST_WEEK", "PAST_2_WEEKS", "PAST_MONTH"]);
export const ApplicationStatusEnum = z.enum([
  "FOUND", "SKIPPED", "DOCUMENTS_READY", "SAVED", "FORM_FILLED", "INCOMPLETE", "ERROR", "APPLIED",
]);

// ── auth ──
const Password = z
  .string()
  .min(10, "Password must be at least 10 characters")
  .max(128)
  .regex(/[a-z]/, "Password needs a lower-case letter")
  .regex(/[A-Z]/, "Password needs an upper-case letter")
  .regex(/[0-9]/, "Password needs a number");

export const RegisterBody = z.object({
  firstName: z.string().trim().min(1).max(100),
  lastName: z.string().trim().min(1).max(100),
  email: z.email().toLowerCase(),
  password: Password,
});

export const LoginBody = z.object({
  email: z.email().toLowerCase(),
  password: z.string().min(1).max(128),
});

// ── users ──
export const UpdateUserBody = z.object({
  firstName: z.string().trim().min(1).max(100).optional(),
  lastName: z.string().trim().min(1).max(100).optional(),
});

const SiteLogin = z.object({ email: z.email(), password: z.string().min(1).max(256) });
/** Job-site credentials. Saved encrypted; never returned by the API. */
export const CredentialsBody = z
  .object({ linkedin: SiteLogin.optional(), glassdoor: SiteLogin.optional() })
  .strict();

const optionalUrl = z.url().optional().nullable();
export const ProfileBody = z.object({
  phone: z.string().max(40).optional().nullable(),
  addressLine: z.string().max(200).optional().nullable(),
  city: z.string().max(100).optional().nullable(),
  region: z.string().max(100).optional().nullable(),
  country: z.string().max(100).optional().nullable(),
  postalCode: z.string().max(20).optional().nullable(),
  linkedinUrl: optionalUrl,
  githubUrl: optionalUrl,
  portfolioUrl: optionalUrl,
  workAuthorization: z.string().max(200).optional().nullable(),
  requiresSponsorship: z.boolean().optional().nullable(),
  yearsOfExperience: z.number().int().min(0).max(60).optional().nullable(),
  desiredSalary: z.string().max(100).optional().nullable(),
  noticePeriod: z.string().max(100).optional().nullable(),
  defaultResumeCategory: z
    .enum(["software_developer", "data_analyst", "business_analyst", "non_it"])
    .optional()
    .nullable(),
  extraAnswers: z.record(z.string(), z.string()).optional().nullable(),
});

// ── search criteria ──
export const SearchCriteriaBody = z.object({
  name: z.string().trim().min(1).max(100),
  query: z.string().trim().min(2).max(200),
  location: z.string().trim().max(200).optional().nullable(),
  country: z.string().length(2).toLowerCase().default("ca"),
  datePosted: DatePostedEnum.default("PAST_WEEK"),
  jobTypes: z.array(JobTypeEnum).default([]),
  locationTypes: z.array(LocationTypeEnum).default([]),
  websites: z.array(WebsiteEnum).min(1).default(["LINKEDIN", "GLASSDOOR"]),
  includeKeywords: z.array(z.string().trim().min(1)).default([]),
  excludeKeywords: z.array(z.string().trim().min(1)).default([]),
  minSalary: z.number().int().positive().optional().nullable(),
  minMatchRating: z.number().int().min(0).max(100).default(60),
  maxFraudRating: z.number().int().min(0).max(100).default(40),
  maxResults: z.number().int().min(1).max(100).default(20),
  autoGenerateDocs: z.boolean().default(true),
  isActive: z.boolean().default(true),
});
export const UpdateSearchCriteriaBody = SearchCriteriaBody.partial();

// ── companies ──
export const CompanyBody = z.object({
  name: z.string().trim().min(1).max(200),
  headOfficeLocation: z.string().max(200).optional().nullable(),
  websiteUrl: optionalUrl,
  /** Adds the company to (true) or removes it from (false) YOUR blacklist. */
  blacklisted: z.boolean().optional(),
});
export const UpdateCompanyBody = CompanyBody.partial();
export const CompanyQuery = z.object({
  blacklisted: z.enum(["true", "false"]).transform((v) => v === "true").optional(),
  search: z.string().max(100).optional(),
});

// ── jobs ──
export const JobListQuery = z.object({
  status: ApplicationStatusEnum.optional(),
  website: WebsiteEnum.optional(),
  locationType: LocationTypeEnum.optional(),
  minMatch: z.coerce.number().int().min(0).max(100).optional(),
  maxFraud: z.coerce.number().int().min(0).max(100).optional(),
  page: z.coerce.number().int().min(1).default(1),
  pageSize: z.coerce.number().int().min(1).max(100).default(25),
});

export const UpdateJobBody = z.object({
  applicationStatus: ApplicationStatusEnum.optional(),
  statusMessage: z.string().max(2000).optional().nullable(),
});

export const UpdateFilesBody = z.object({
  /** Path or URL of a different resume / cover letter to use for this job. null = back to the AI version. */
  resumeLink: z.string().min(1).max(1000).nullable().optional(),
  coverLetterLink: z.string().min(1).max(1000).nullable().optional(),
});

// ── answers ──
export const UpdateAnswerBody = z.object({ answer: z.string().min(1).max(5000) });

// ── audit logs ──
export const AuditQuery = z.object({
  type: z
    .enum(["HTTP_REQUEST", "HTTP_RESPONSE", "EXTERNAL_API_CALL", "AI_CALL", "AUTOFILL", "AUTH", "ERROR"])
    .optional(),
  requestId: z.string().optional(),
  limit: z.coerce.number().int().min(1).max(500).default(100),
});

// ── application log (Excel) ──
const IsoDate = z
  .string()
  .regex(/^\d{4}-\d{2}-\d{2}$/, "Use the format YYYY-MM-DD")
  .refine((v) => {
    const [y, m, d] = v.split("-").map(Number) as [number, number, number];
    const dt = new Date(y, m - 1, d);
    return dt.getFullYear() === y && dt.getMonth() === m - 1 && dt.getDate() === d;
  }, "Not a real date");
/** date = the day you applied (local time). Leave it out for today. */
export const ApplicationLogBody = z.object({ date: IsoDate.optional() });
export const ApplicationLogQuery = z.object({ date: IsoDate.optional() });
